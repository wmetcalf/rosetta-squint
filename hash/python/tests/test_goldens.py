"""Group-2 byte-exact tests: every rosetta_squint_hash algorithm matches
spec/goldens.json on every fixture and size.

The goldens are generated by spec/regenerate.py, which carries its own copy
of each algorithm body. This test checks the *shipped* package against them,
so a change in the package, or in the Pillow / numpy / scipy / PyWavelets
versions it resolves to, that moves any hash fails here. The other five ports
test against the same file.

The weekly PyPI drift job (.github/workflows/pypi-drift.yml) runs this file
against a fresh `pip install` from PyPI, with whatever dependency versions
users currently get.
"""

from __future__ import annotations

import json
import struct
from pathlib import Path
from typing import Callable

import numpy as np
import pytest
from PIL import Image

import rosetta_squint_hash as rih

SPEC = Path(__file__).resolve().parent.parent.parent / "spec"
GOLDENS = json.loads((SPEC / "goldens.json").read_text())

# goldens.json algorithm name -> call taking (image, size-or-binbits).
ALGORITHMS: dict[str, Callable[[Image.Image, int], object]] = {
    "average_hash": lambda img, n: rih.average_hash(img, hash_size=n),
    "dhash": lambda img, n: rih.dhash(img, hash_size=n),
    "dhash_vertical": lambda img, n: rih.dhash_vertical(img, hash_size=n),
    "phash": lambda img, n: rih.phash(img, hash_size=n),
    "phash_simple": lambda img, n: rih.phash_simple(img, hash_size=n),
    "whash_haar": lambda img, n: rih.whash(img, hash_size=n),
    "whash_db4": lambda img, n: rih.whash_db4(img, hash_size=n),
    "whash_db4_robust": lambda img, n: rih.whash_db4_robust(img, hash_size=n),
    "colorhash": lambda img, n: rih.colorhash(img, binbits=n),
}


def _load_predecoded(fixture: str) -> Image.Image:
    """spec/decoded/<fixture>.rgb.bin, the canonical RGB buffer every port reads."""
    blob = (SPEC / "decoded" / f"{fixture}.rgb.bin").read_bytes()
    w, h = struct.unpack("<II", blob[:8])
    return Image.fromarray(np.frombuffer(blob[8:], dtype=np.uint8).reshape((h, w, 3)), mode="RGB")


def _cases() -> list[tuple[str, str, int, str]]:
    cases = []
    for algo in ALGORITHMS:
        for fixture, sizes in sorted(GOLDENS["algorithms"][algo]["fixtures"].items()):
            for size, expected in sorted(sizes.items(), key=lambda kv: int(kv[0])):
                if expected is not None:  # null: fixture too small for this size
                    cases.append((algo, fixture, int(size), expected))
    return cases


def test_every_algorithm_is_covered():
    assert set(GOLDENS["algorithms"]) == set(ALGORITHMS) | {"crop_resistant_hash"}


@pytest.mark.parametrize("algo,fixture,size,expected", _cases(), ids=lambda v: str(v))
def test_matches_goldens(algo: str, fixture: str, size: int, expected: str):
    got = str(ALGORITHMS[algo](_load_predecoded(fixture), size))
    assert got == expected, f"{algo}({size}) on {fixture}: got {got}, want {expected}"


@pytest.mark.parametrize(
    "fixture,expected",
    sorted((f, d["default"]) for f, d in GOLDENS["algorithms"]["crop_resistant_hash"]["fixtures"].items()),
    ids=lambda v: str(v)[:40],
)
def test_crop_resistant_hash_matches_goldens(fixture: str, expected: str):
    got = str(rih.crop_resistant_hash(_load_predecoded(fixture)))
    assert got == expected, f"crop_resistant_hash on {fixture}: got {got}, want {expected}"
